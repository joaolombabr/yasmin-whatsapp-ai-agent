/**
 * False-confirmation interceptor: the last check before a message reaches the customer.
 *
 * Runs in the Master workflow (n8n Code node), after the ordering specialist has
 * written its reply and before that reply is humanized and sent:
 *
 *   Ordering specialist -> read order_created / active_order / pending summary (Redis)
 *     -> THIS NODE -> "literal?" IF -> literal:  split into messages and send as is
 *                                      otherwise: validator/humanizer agent -> send
 *
 * Why it exists: the agent sometimes told a customer "order confirmed!" when the
 * order-creation tool had never succeeded, or had never been called. The customer
 * then waits for food no kitchen knows about. The model does not get to be the
 * source of truth about whether something happened; Redis keys written only on
 * a successful vendor response do.
 *
 * It has three jobs, and two of them came from its own failures:
 *
 * 1. BLOCK a reply that announces an order when no order exists (the original job).
 *    It has caught a false confirmation live.
 *
 * 2. DON'T BLOCK a true statement. The first version checked only order_created
 *    (TTL 120 s). A customer asked about their order three minutes after placing it,
 *    and the interceptor replaced a correct answer with "your order was not
 *    registered", which was false. The check now also accepts the active-order key
 *    (TTL 2 h). A guard's false positives reach the customer too.
 *
 * 3. KEEP CODE-BUILT TEXT LITERAL. Order summaries and the closing message are built
 *    by code from the vendor's response. The humanizer agent used to rewrite them
 *    (it reworded "order no. N has been placed" in testing), so those messages now
 *    skip it. When the model leaves out part of the closing message (the Pix
 *    payment block, or the drink question), it is restored from the create_order
 *    tool's own return value, read through the agent's intermediate steps.
 *
 * REDACTED FOR PUBLICATION: node names, field names, comments and customer-facing
 * strings are translated from Portuguese; dates and order numbers removed. Control flow and
 * regular expressions are unmodified (the expressions match Portuguese text,
 * which is what customers and the agent write).
 */

function readNode(name) {
  try { return $(name).first().json || {}; } catch (e) { return {}; }
}

const specialist = readNode('Ordering Specialist');
const text = String(specialist.output || '');

const turnStart = Number(readNode('Message').turnStart) || 0;
const orderCreated = String(readNode('Get Order Created').orderCreated || '').trim(); // TTL 120 s, set on vendor success
const activeOrder = String(readNode('Get Active Order').activeOrder || '').trim();    // TTL 2 h

let summary = null;
try {
  summary = JSON.parse(String(readNode('Get Pending Summary').summary || 'null'));
} catch (e) {
  summary = null;
}

// 1) A summary was generated by code in THIS turn and not yet confirmed -> send it literally.
if (summary && summary.msg && Number(summary.ts) >= turnStart && !orderCreated) {
  return [{ json: { ...specialist, output: summary.msg, literal: true, textSource: 'order_summary' } }];
}

// 2) Order created in THIS turn and the reply is the closing message -> literal,
//    with any missing code-built part restored from the tool result.
const isClosing = /seu pedido n\S{0,2}\s*\d+/i.test(text) && /(lan[cç]ado|cozinha|chave pix)/i.test(text);
if (orderCreated && isClosing) {
  let complete = text;
  try {
    const steps = Array.isArray(specialist.intermediateSteps) ? specialist.intermediateSteps : [];
    let closing = null;
    steps.forEach(s => {
      const toolName = String(((s || {}).action || {}).tool || '');
      if (!/criar_pedido/i.test(toolName)) return;          // the create_order tool
      let obs = (s || {}).observation;
      try { obs = typeof obs === 'string' ? JSON.parse(obs) : obs; } catch (e) { obs = null; }
      const r = Array.isArray(obs) ? obs[0] : obs;
      if (r && r.ok === true) closing = r;
    });
    const squash = x => String(x || '').replace(/\s+/g, ' ').trim();
    if (closing) {
      if (closing.pixMessage && !squash(complete).includes(squash(closing.pixMessage).slice(0, 40))) {
        complete = complete.trim() + '\n' + String(closing.pixMessage).trim();
      }
      if (closing.drinkMessage && !squash(complete).includes(squash(closing.drinkMessage).slice(0, 30))) {
        complete = complete.trim() + '\n' + String(closing.drinkMessage).trim();
      }
    }
  } catch (e) {
    complete = text;
  }
  return [{ json: { ...specialist, output: complete, literal: true, textSource: 'order_closing' } }];
}

// Does the reply claim that an order was placed / confirmed / sent to the kitchen?
const announcesOrder = /pedido[\s\S]{0,80}?(confirmado|confirmei|feito|fechado|registrado|criado|finalizado|lancado|lançado|enviado|aceito)/i.test(text)
  || /(confirmado|registrado|finalizado|lancado|lançado|enviado|aceito)[\s\S]{0,40}?pedido/i.test(text)
  || /pedido[\s\S]{0,40}?cozinha/i.test(text)
  || /qualquer\s+(novidade|coisa)[\s\S]{0,20}?(aviso|falo)/i.test(text);

// 3) Announces an order while NO order exists -> replace the message before it is sent.
if (announcesOrder && !orderCreated && !activeOrder) {
  return [{ json: {
    ...specialist,
    output: "I haven't placed your order yet. Tell me what you'd like and I'll finish it now.",
    falseConfirmationBlocked: true
  } }];
}

return [{ json: specialist }];
